#!/usr/bin/env bash
# Fallback: download 2DGS DTU from Google Drive when Hugging Face is unreachable.
set -e
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UGGS_ROOT="$(dirname "$SCRIPT_DIR")"
cd "$UGGS_ROOT"
DTU_DIR="${UGGS_ROOT}/data/dtu"
mkdir -p "$DTU_DIR"
mkdir -p "$UGGS_ROOT/configs"
echo "# Generated by scripts/download_dtu_gdrive.sh" > "$UGGS_ROOT/configs/dtu_path.env"
echo "export UGGS_DTU_ROOT=$DTU_DIR" >> "$UGGS_ROOT/configs/dtu_path.env"

GDRIVE_FOLDER_ID="1SJFgt8qhQomHX55Q4xSvYE2C6-8tFll9"
echo "Downloading DTU from Google Drive to: $DTU_DIR"
pip install -q gdown
TMP_PARENT="${UGGS_ROOT}/data"
if gdown "$GDRIVE_FOLDER_ID" -O "$TMP_PARENT" --folder; then
  for sub in "$TMP_PARENT"/*/; do
    if [ -d "$sub" ] && [ "$(basename "$sub")" != "dtu" ]; then
      mv "$sub"* "$DTU_DIR/" 2>/dev/null || true
      rmdir "$sub" 2>/dev/null || true
      break
    fi
  done
  echo "Done (Google Drive). DTU root: $DTU_DIR"
else
  echo "gdown failed. Download manually: https://drive.google.com/drive/folders/${GDRIVE_FOLDER_ID}"
  exit 1
fi
