#!/usr/bin/env bash
# Download 2DGS preprocessed DTU to the project data path and set UGGS_DTU_ROOT.
set -e
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UGGS_ROOT="$(dirname "$SCRIPT_DIR")"
cd "$UGGS_ROOT"
DTU_DIR="${UGGS_ROOT}/data/dtu"
mkdir -p "$DTU_DIR"
mkdir -p "$UGGS_ROOT/configs"
echo "# Generated by scripts/download_dtu.sh" > "$UGGS_ROOT/configs/dtu_path.env"
echo "export UGGS_DTU_ROOT=$DTU_DIR" >> "$UGGS_ROOT/configs/dtu_path.env"

echo "Downloading DTU (2DGS preprocessed) to: $DTU_DIR"
pip install -q huggingface_hub
export HF_HUB_DOWNLOAD_TIMEOUT=300
if python -c "
from huggingface_hub import snapshot_download
snapshot_download(repo_id='dylanebert/2DGS', repo_type='dataset', local_dir='$DTU_DIR')
"; then
  echo "Done (Hugging Face). DTU root: $DTU_DIR"
else
  echo "Hugging Face failed. Try: ./scripts/download_dtu_gdrive.sh"
  exit 1
fi
echo "Source for later: source $UGGS_ROOT/configs/dtu_path.env"
