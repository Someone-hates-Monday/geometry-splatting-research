"""Verify actual archived/current bytes and fresh held-out branch admission."""
from __future__ import annotations
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import sys
import zipfile
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read(path):
    return json.loads(path.read_text())


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--run', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    args = p.parse_args()
    run = args.run.resolve()
    if args.out.exists():
        p.error('Fresh report required.')
    state = read(run / 'manifest.json')
    preflight = read(Path(state['preflight']))
    if sha(Path(state['preflight'])) != state['preflight_sha256'] or sha(run / 'sources.zip') != state['source_archive_sha256']:
        raise ValueError('Input preflight/archive changed.')
    actual_binaries = {}
    for label, pattern in (('legacy64', 'precise_precise2_*/uggs_precise_precise2_*.so'),
                           ('factor64', 'factor64_*/uggs_factor64_*.so')):
        matches = [x for x in (ROOT / 'research/build').glob(pattern) if sha(x) == state['backend_sha256'][label]]
        if len(matches) != 1:
            raise ValueError('Expected one actually matching backend binary: ' + label)
        actual_binaries[label] = matches[0]
    generated_count = 0
    with zipfile.ZipFile(run / 'sources.zip') as archive:
        for name, digest in state['source_sha256'].items():
            if sha(ROOT / name) != digest or hashlib.sha256(archive.read(name)).hexdigest() != digest:
                raise ValueError('Current/archived source mismatch: ' + name)
        if hashlib.sha256(archive.read('preflight.json')).hexdigest() != state['preflight_sha256']:
            raise ValueError('Archived preflight differs.')
        for name in archive.namelist():
            if name.startswith('generated/'):
                _, label, relative = name.split('/', 2)
                actual = actual_binaries[label].parent / 'src' / relative
                if actual.read_bytes() != archive.read(name):
                    raise ValueError('Actual generated bytes differ: ' + name)
                generated_count += 1
    for name, digest in preflight['input_sha256'].items():
        if sha(Path(name)) != digest:
            raise ValueError('Actual dataset/calibration changed.')
    common = run / 'common'
    checkpoint, sidecar = common / 'chkpnt6999.pth', common / 'chkpnt6999.runtime.pth'
    if sha(checkpoint) != state['common_checkpoint_sha256'] or sha(sidecar) != state['sidecar_sha256']:
        raise ValueError('Common checkpoint bytes differ.')
    saved = torch.load(sidecar, map_location='cpu', weights_only=False)
    if saved['iteration'] != 6999 or saved['initial_state_sha256'] != state['initial_state_sha256'] or saved['checkpoint_sha256'] != sha(checkpoint):
        raise ValueError('Sidecar content differs.')
    warm = read(common / 'solver_training_integration.json')
    if not warm['completed'] or warm['ncc_calls'] != 0 or warm['initial_state_sha256'] != state['initial_state_sha256']:
        raise ValueError('Warmup integration mismatch.')
    stage = next(x for x in state['steps'] if x['stage'] == 'warmup')
    if '--start_checkpoint' in stage['argv'] or '--eval' not in stage['argv'] or stage['returncode'] != 0:
        raise ValueError('Warmup was not a fresh eval=True invocation.')
    smokes, cameras = {}, {}
    for label in ('legacy64', 'factor64'):
        model = run / (label + '_smoke')
        filename = 'corrected_training_integration.json' if label == 'legacy64' else 'factor_training_integration.json'
        rec = read(model / filename)
        if rec['status'] != 'complete' or rec['steps_observed'] != 20 or rec['nonfinite_gradient_groups']:
            raise ValueError('Finite 20-update smoke failed.')
        if rec['backend_sha256'] != state['backend_sha256'][label]:
            raise ValueError('Smoke binary mismatch.')
        smokes[label] = rec
    keys = ('initial_state_sha256', 'first_camera', 'initial_gaussians', 'common_checkpoint_sha256', 'sidecar_sha256', 'first_loss_scalars')
    for key in keys:
        if smokes['legacy64'][key] != smokes['factor64'][key]:
            raise ValueError('Matched smoke state/first loss differs: ' + key)
    if smokes['legacy64']['initial_state_sha256'] != saved['initial_state_sha256']:
        raise ValueError('Smoke differs from fresh common sidecar.')
    for label in ('common', 'legacy64_smoke', 'factor64_smoke'):
        path = run / label / 'holdout_camera_integration.json'
        rec = read(path)
        if rec['status'] != 'complete' or rec['pool'] != preflight['pool'] or rec['final_test_report_render_calls'] != 0:
            raise ValueError('Actual camera guards differ.')
        if set(rec['ncc_target_names_seen']) & set(state['test_names']):
            raise ValueError('NCC target leakage.')
        cameras[label] = {'sha256': sha(path), **{k: rec[k] for k in ('train_render_calls', 'filter_calls', 'ncc_calls', 'final_test_report_render_calls')}}
    if state['initial_state_sha256'] == read(ROOT / 'research/experiments/adjquad55_v1/manifest.json')['initial_state_sha256']:
        raise ValueError('Fresh state unexpectedly equals the old all-view state.')
    result = {'checked_utc': datetime.now(timezone.utc).isoformat(), 'run': str(run),
              'actual_sources_archive_inputs_binaries_and_smokes_verified': True,
              'source_count': len(state['source_sha256']), 'actual_generated_file_count': generated_count,
              'dataset_calibration_file_count': len(preflight['input_sha256']),
              'fresh_zero_start_warmup_verified': True, 'initial_state_sha256': state['initial_state_sha256'],
              'first_camera': smokes['legacy64']['first_camera'], 'first_loss_scalars_identical': True,
              'train_count': len(state['train_names']), 'test_count': len(state['test_names']),
              'camera_execution_counts': cameras, 'pilot_gate': state['pilot_gate'],
              'matched_camera_alignment_rms_mm': preflight['correct_id_alignment']['center_rms_mm'],
              'wrong_first_N_alignment_rms_mm': preflight['wrong_first_N_alignment']['center_rms_mm'],
              'manifest_status_at_snapshot': state['status'], 'stage_at_snapshot': state['current_stage'],
              'source_archive_sha256': state['source_archive_sha256'], 'limits': state['limits'] +
              ['This admission report does not certify future/full training or model-quality outcomes.',
               'Actual process liveness must be refreshed separately; manifest running alone is insufficient.']}
    args.out.write_text(json.dumps(result, indent=2, allow_nan=False) + '\n')
    print(json.dumps({k: v for k, v in result.items() if k not in ('limits', 'camera_execution_counts')}, indent=2))


if __name__ == '__main__':
    main()
